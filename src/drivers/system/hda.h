#ifndef HDA_H
#define HDA_H

#include <stdint.h>
#include <stdbool.h>

/*
 * Драйвер Intel HD Audio.
 *
 * Реализована только инициализация (сброс контроллера, проверка наличия
 * кодеков) — фактическое воспроизведение для HDA пока не реализовано,
 * функции-заглушки оставлены для единого интерфейса звуковой подсистемы.
 */

/* Сканирует PCI и инициализирует первый найденный HDA-контроллер.
 * Возвращает true, если контроллер найден и кодек(и) отвечают. */
bool hda_init(void);

/* Заглушка: управление громкостью для HDA пока не реализовано. */
void hda_set_volume(uint8_t vol);

/* Заглушка: воспроизведение для HDA пока не реализовано. */
void hda_play_pcm(const uint8_t *pcm_data, uint32_t length);

#endif
